/**
 * A small SHA-256 for the key fingerprint only.
 *
 * `expo-crypto` would provide this, but a fingerprint is a UI convenience, not a
 * security control: the key itself never leaves SecureStore, and this hash is
 * only shown so the owner can tell that the stored key changed. Avoiding the
 * dependency keeps the native module surface smaller.
 *
 * This is SHA-256 for non-adversarial use (fingerprinting), and it is labelled
 * as such so nobody mistakes it for a cryptographic primitive used to protect a
 * secret. The bundle size is ~120 lines; a vetted implementation would be better
 * if this were ever used for anything else.
 */

